//! Five Elements (五行) and Yin-Yang (陰陽)
//!
//! Defines generating (相生) and controlling (相克) relations among Wood, Fire, Earth, Metal, and Water.

use serde::{Deserialize, Serialize};

/// Five Elements (五行)
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Element {
    /// Wood (木)
    Wood,
    /// Fire (火)
    Fire,
    /// Earth (土)
    Earth,
    /// Metal (金)
    Metal,
    /// Water (水)
    Water,
}

/// Yin-Yang Polarity (陰陽)
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Polarity {
    /// Yang (陽)
    Yang,
    /// Yin (陰)
    Yin,
}

/// Element Relation Type
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ElementRelation {
    /// Same element
    Same,
    /// Generates: self produces other
    Generates,
    /// Generated by: other produces self
    GeneratedBy,
    /// Controls: self restricts other
    Controls,
    /// Controlled by: other restricts self
    ControlledBy,
}

impl Element {
    /// All elements array
    pub const ALL: [Element; 5] = [
        Self::Wood,
        Self::Fire,
        Self::Earth,
        Self::Metal,
        Self::Water,
    ];

    /// Hanja notation
    pub const HANJA: [&'static str; 5] = ["木", "火", "土", "金", "水"];

    /// English name notation
    pub const HANGUL: [&'static str; 5] = ["Wood", "Fire", "Earth", "Metal", "Water"];

    /// Index (0-4)
    #[inline]
    pub const fn index(self) -> u8 {
        match self {
            Self::Wood => 0,
            Self::Fire => 1,
            Self::Earth => 2,
            Self::Metal => 3,
            Self::Water => 4,
        }
    }

    /// Construct from index
    #[inline]
    pub const fn from_index(idx: i32) -> Self {
        Self::ALL[idx.rem_euclid(5) as usize]
    }

    /// Generating: Element produced by self (Wood -> Fire -> Earth -> Metal -> Water -> Wood)
    #[inline]
    pub const fn generates(self) -> Element {
        match self {
            Self::Wood => Self::Fire,
            Self::Fire => Self::Earth,
            Self::Earth => Self::Metal,
            Self::Metal => Self::Water,
            Self::Water => Self::Wood,
        }
    }

    /// Generating: Element that produces self
    #[inline]
    pub const fn generated_by(self) -> Element {
        match self {
            Self::Wood => Self::Water,
            Self::Fire => Self::Wood,
            Self::Earth => Self::Fire,
            Self::Metal => Self::Earth,
            Self::Water => Self::Metal,
        }
    }

    /// Controlling: Element controlled by self (Wood -> Earth -> Water -> Fire -> Metal -> Wood)
    #[inline]
    pub const fn controls(self) -> Element {
        match self {
            Self::Wood => Self::Earth,
            Self::Fire => Self::Metal,
            Self::Earth => Self::Water,
            Self::Metal => Self::Wood,
            Self::Water => Self::Fire,
        }
    }

    /// Controlling: Element that controls self
    #[inline]
    pub const fn controlled_by(self) -> Element {
        match self {
            Self::Wood => Self::Metal,
            Self::Fire => Self::Water,
            Self::Earth => Self::Wood,
            Self::Metal => Self::Fire,
            Self::Water => Self::Earth,
        }
    }

    /// Determine relation to another element
    #[inline]
    pub const fn relation_to(self, other: Element) -> ElementRelation {
        if self.index() == other.index() {
            ElementRelation::Same
        } else if self.generates().index() == other.index() {
            ElementRelation::Generates
        } else if self.generated_by().index() == other.index() {
            ElementRelation::GeneratedBy
        } else if self.controls().index() == other.index() {
            ElementRelation::Controls
        } else {
            ElementRelation::ControlledBy
        }
    }

    /// Hanja notation
    #[inline]
    pub const fn hanja(self) -> &'static str {
        Self::HANJA[self.index() as usize]
    }

    /// English name notation
    #[inline]
    pub const fn hangul(self) -> &'static str {
        Self::HANGUL[self.index() as usize]
    }

    /// English name alias
    #[inline]
    pub const fn english(self) -> &'static str {
        Self::HANGUL[self.index() as usize]
    }
}

impl Polarity {
    /// Hanja notation
    #[inline]
    pub const fn hanja(self) -> &'static str {
        match self {
            Self::Yang => "陽",
            Self::Yin => "陰",
        }
    }

    /// English name notation
    #[inline]
    pub const fn hangul(self) -> &'static str {
        match self {
            Self::Yang => "Yang",
            Self::Yin => "Yin",
        }
    }

    /// English name alias
    #[inline]
    pub const fn english(self) -> &'static str {
        self.hangul()
    }

    /// Opposite polarity
    #[inline]
    pub const fn opposite(self) -> Self {
        match self {
            Self::Yang => Self::Yin,
            Self::Yin => Self::Yang,
        }
    }
}

impl std::fmt::Display for Element {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.hanja())
    }
}

impl std::fmt::Display for Polarity {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.hanja())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_element_generates() {
        assert_eq!(Element::Wood.generates(), Element::Fire);
        assert_eq!(Element::Fire.generates(), Element::Earth);
        assert_eq!(Element::Earth.generates(), Element::Metal);
        assert_eq!(Element::Metal.generates(), Element::Water);
        assert_eq!(Element::Water.generates(), Element::Wood);
    }

    #[test]
    fn test_element_controls() {
        assert_eq!(Element::Wood.controls(), Element::Earth);
        assert_eq!(Element::Fire.controls(), Element::Metal);
        assert_eq!(Element::Earth.controls(), Element::Water);
        assert_eq!(Element::Metal.controls(), Element::Wood);
        assert_eq!(Element::Water.controls(), Element::Fire);
    }

    #[test]
    fn test_element_relation() {
        assert_eq!(
            Element::Wood.relation_to(Element::Wood),
            ElementRelation::Same
        );
        assert_eq!(
            Element::Wood.relation_to(Element::Fire),
            ElementRelation::Generates
        );
        assert_eq!(
            Element::Wood.relation_to(Element::Water),
            ElementRelation::GeneratedBy
        );
        assert_eq!(
            Element::Wood.relation_to(Element::Earth),
            ElementRelation::Controls
        );
        assert_eq!(
            Element::Wood.relation_to(Element::Metal),
            ElementRelation::ControlledBy
        );
    }

    #[test]
    fn test_polarity_opposite() {
        assert_eq!(Polarity::Yang.opposite(), Polarity::Yin);
        assert_eq!(Polarity::Yin.opposite(), Polarity::Yang);
    }
}
